export function getSuggestedEmojis(text, type = 'expense') {
  if (!text || typeof text !== 'string') {
    return type === 'income' 
      ? ['💰', '💼', '📈', '💵', '🟢', '🏆', '💎', '🤑'] 
      : ['🍔', '🏠', '🚗', '🏥', '🎮', '🏋️', '🛍️', '💡'];
  }

  const normalized = text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();

  if (normalized.length === 0) {
    return type === 'income' 
      ? ['💰', '💼', '📈', '💵', '🟢', '🏆', '💎', '🤑'] 
      : ['🍔', '🏠', '🚗', '🏥', '🎮', '🏋️', '🛍️', '💡'];
  }

  const matches = new Set();

  for (const group of KEYWORD_SUGGESTIONS) {
    for (const kw of group.keywords) {
      const cleanKw = kw.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
      if (normalized.includes(cleanKw) || cleanKw.includes(normalized)) {
        group.emojis.forEach(e => matches.add(e));
      }
    }
  }

  if (matches.size > 0) {
    return Array.from(matches).slice(0, 10);
  }

  if (type === 'income') {
    return ['💰', '💼', '📈', '💵', '🟢', '🏆', '💎', '🤑', '⭐', '✨'];
  }

  return ['🏷️', '🍔', '🏠', '🚗', '🏥', '🎮', '🏋️', '🛍️', '💡', '✈️'];
}
